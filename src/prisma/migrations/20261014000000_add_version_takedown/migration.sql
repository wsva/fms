-- AlterTable: published-version availability for the takedown primitive (sync-v2 §11.5).
-- 'Y'/'N' matches the catalog's `deleted` convention. Default 'Y' keeps every existing
-- published version available, so no backfill is needed.
--
-- This is the ONLY sanctioned metadata mutation of an otherwise immutable `versions/`
-- entry (INV-8): the bytes are never touched here. A version marked 'N' makes registry
-- reads return 410 Gone and the read-time pin resolve to the next-lower available
-- version. `dataset.current_version` is deliberately NOT rewritten by a takedown —
-- INV-17 reserves pin moves to an explicit publish — so an overturned takedown restores
-- the exact prior state by flipping this back to 'Y'.
ALTER TABLE "dataset_version" ADD COLUMN "available" VARCHAR(1) NOT NULL DEFAULT 'Y';
